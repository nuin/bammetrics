// Writes crates/core/picard_fields.tsv: every htsjdk MetricBase subclass and
// Header class in picard.jar, with the public fields in Class.getFields() order
// as htsjdk reads and compares them. Run with `make picard-fields`, which calls
//   java -cp picard.jar tests/data/PicardFields.java picard.jar > crates/core/picard_fields.tsv
//
// Lines:
//   M <class> <instantiable Y|N>           a metrics class
//   F <name> <type> <static Y|N> <default>  one public field of the class above
//   H <class>                               a Header class MetricsFile can load
// <type> is a JVM primitive name (long, int, short, byte, double, float,
// boolean, char), java.lang.X for a boxed number, String or Boolean,
// enum:<canonical name>:<A,B,C> for an enum with its constants, or the class name of any other
// type. <default> is String.valueOf of the field on a new instance, \N for null
// or a class that cannot be instantiated, with \\ for a backslash and \\uXXXX
// for a control character.
import java.lang.reflect.Field;
import java.lang.reflect.Modifier;
import java.util.ArrayList;
import java.util.Collections;
import java.util.Enumeration;
import java.util.List;
import java.util.jar.JarEntry;
import java.util.jar.JarFile;

public class PicardFields {
    public static void main(String[] args) throws Exception {
        ClassLoader loader = PicardFields.class.getClassLoader();
        Class<?> metricBase = Class.forName("htsjdk.samtools.metrics.MetricBase", false, loader);
        Class<?> header = Class.forName("htsjdk.samtools.metrics.Header", false, loader);
        List<String> names = new ArrayList<>();
        try (JarFile jar = new JarFile(args[0])) {
            Enumeration<JarEntry> entries = jar.entries();
            while (entries.hasMoreElements()) {
                String entry = entries.nextElement().getName();
                if (entry.endsWith(".class") && !entry.startsWith("META-INF")) {
                    names.add(entry.substring(0, entry.length() - 6).replace('/', '.'));
                }
            }
        }
        Collections.sort(names);
        StringBuilder out = new StringBuilder();
        out.append("# Generated by tests/data/PicardFields.java from Picard 3.5.0 (make picard-fields). Do not edit.\n");
        for (String name : names) {
            Class<?> type;
            try {
                type = Class.forName(name, false, loader);
            } catch (Throwable e) {
                continue;
            }
            if (header.isAssignableFrom(type) && !type.isInterface()
                    && !Modifier.isAbstract(type.getModifiers())) {
                out.append("H\t").append(type.getName()).append('\n');
                continue;
            }
            if (!metricBase.isAssignableFrom(type) || type.isInterface()) {
                continue;
            }
            Object instance = null;
            try {
                instance = type.getDeclaredConstructor().newInstance();
            } catch (Throwable e) {
                instance = null;
            }
            Field[] fields;
            try {
                fields = type.getFields();
            } catch (Throwable e) {
                continue;
            }
            out.append("M\t").append(type.getName()).append('\t')
                    .append(instance == null ? "N" : "Y").append('\n');
            for (Field field : fields) {
                boolean isStatic = Modifier.isStatic(field.getModifiers());
                String value = "\\N";
                try {
                    Object v = isStatic ? field.get(null) : (instance == null ? null : field.get(instance));
                    if (v != null) {
                        value = escape(String.valueOf(v));
                    }
                } catch (Throwable e) {
                    value = "\\N";
                }
                out.append("F\t").append(field.getName()).append('\t').append(typeName(field.getType()))
                        .append('\t').append(isStatic ? "Y" : "N").append('\t').append(value).append('\n');
            }
        }
        System.out.print(out);
    }

    /** A backslash as \\, a control character as \\uXXXX: one line, one tab-free cell. */
    static String escape(String text) {
        StringBuilder s = new StringBuilder();
        for (char c : text.toCharArray()) {
            if (c == '\\') {
                s.append("\\\\");
            } else if (c < 0x20) {
                s.append(String.format("\\u%04x", (int) c));
            } else {
                s.append(c);
            }
        }
        return s.toString();
    }

    static String typeName(Class<?> type) {
        if (type.isEnum()) {
            StringBuilder s = new StringBuilder("enum:").append(type.getCanonicalName()).append(':');
            Object[] constants = type.getEnumConstants();
            for (int i = 0; i < constants.length; i++) {
                if (i > 0) s.append(',');
                s.append(((Enum<?>) constants[i]).name());
            }
            return s.toString();
        }
        return type.getName();
    }
}
